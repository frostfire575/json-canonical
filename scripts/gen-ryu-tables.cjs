'use strict';
// Writes crates/core/src/ryu_tables.rs: the 125-bit power-of-5 tables used by Ryu
// (Ulf Adams, https://github.com/ulfjack/ryu), defined as in its table generator.
const fs = require('node:fs');
const path = require('node:path');

const BITS = 125;
const POW5_COUNT = 326;
const POW5_INV_COUNT = 292;
const mask = (1n << 64n) - 1n;
const bitLength = n => n.toString(2).length;
const entry = n => `(${n & mask}, ${n >> 64n})`;

const pow5 = [];
const inv = [];
for (let i = 0; i < Math.max(POW5_COUNT, POW5_INV_COUNT); i++) {
  const p = 5n ** BigInt(i);
  const len = bitLength(p);
  if (i < POW5_COUNT) pow5.push(len >= BITS ? p >> BigInt(len - BITS) : p << BigInt(BITS - len));
  if (i < POW5_INV_COUNT) inv.push((1n << BigInt(len - 1 + BITS)) / p + 1n);
}

const table = (name, values) =>
  `pub(crate) static ${name}: [(u64, u64); ${values.length}] = [\n${values.map(v => `    ${entry(v)},\n`).join('')}];\n`;

const out = `// Generated by scripts/gen-ryu-tables.cjs. Do not edit.
// (low, high) 64-bit halves. POW5[i] is 5^i scaled to ${BITS} bits; POW5_INV[i] is
// floor(2^(bitlen(5^i) - 1 + ${BITS}) / 5^i) + 1.

#![allow(clippy::unreadable_literal)]

${table('POW5', pow5)}
${table('POW5_INV', inv)}`;
fs.writeFileSync(path.resolve(__dirname, '../crates/core/src/ryu_tables.rs'), out);
console.log(`wrote ${pow5.length} + ${inv.length} entries`);
